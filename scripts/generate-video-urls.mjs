import { config as loadEnv } from 'dotenv'
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { GetObjectCommand, S3Client } from '@aws-sdk/client-s3'
import { getSignedUrl } from '@aws-sdk/s3-request-presigner'
import {
  TIGRIS_BUCKET,
  TIGRIS_ENDPOINT,
  TIGRIS_REGION,
} from './tigris-config.mjs'

const VIDEO_KEYS = {
  general: 'general.mp4',
  stefan: 'stefan.mp4',
  caro: 'caro.mp4',
}

const PRESIGN_EXPIRES_SECONDS = 60 * 60 * 24 * 7 // 7 days (SigV4 max)

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(__dirname, '..')

loadEnv({ path: path.join(repoRoot, '.env'), quiet: true })

const endpoint = process.env.AWS_ENDPOINT_URL ?? TIGRIS_ENDPOINT
const bucket =
  process.env.AWS_S3_BUCKET_NAME ?? process.env.AWS_S3_BUCKET ?? TIGRIS_BUCKET
const region =
  process.env.AWS_DEFAULT_REGION ?? process.env.AWS_REGION ?? TIGRIS_REGION

const accessKeyId = process.env.AWS_ACCESS_KEY_ID
const secretAccessKey = process.env.AWS_SECRET_ACCESS_KEY

if (!accessKeyId || !secretAccessKey) {
  console.error(
    'Missing AWS_ACCESS_KEY_ID or AWS_SECRET_ACCESS_KEY (set in .env locally or as Docker build-args / GitHub Actions secrets).',
  )
  process.exit(1)
}

const client = new S3Client({
  region,
  endpoint,
  credentials: { accessKeyId, secretAccessKey },
  forcePathStyle: true,
})

const urls = {}

for (const [name, key] of Object.entries(VIDEO_KEYS)) {
  urls[name] = await getSignedUrl(
    client,
    new GetObjectCommand({ Bucket: bucket, Key: key }),
    { expiresIn: PRESIGN_EXPIRES_SECONDS },
  )
  console.log(`Presigned ${name}: ${key}`)
}

const outDir = path.join(repoRoot, 'src', 'generated')
await mkdir(outDir, { recursive: true })

const content = `// Generated by npm run videos:presign — do not edit
// Expires ~7 days after generation; re-run before redeploy if needed.

export const VIDEO_URLS = ${JSON.stringify(urls, null, 2)} as const
`

await writeFile(path.join(outDir, 'video-urls.ts'), content)
console.log('Wrote src/generated/video-urls.ts')
